#!/usr/bin/env bash
# =============================================================================
# cf-update-ips.sh, Update Cloudflare IP ranges for nginx real_ip config
# =============================================================================
# Usage: ./scripts/cf-update-ips.sh
#
# Fetches current Cloudflare IP ranges and regenerates
# config/nginx/conf.d/cloudflare-real-ip.conf atomically.
#
# Can be run manually or via cron:
#   0 3 * * 0 /opt/docker/wordpressmultisite/scripts/cf-update-ips.sh
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
CONF_FILE="$PROJECT_DIR/config/nginx/conf.d/cloudflare-real-ip.conf"
TMP_FILE="${CONF_FILE}.tmp.$$"

cleanup() {
    rm -f "$TMP_FILE"
}
trap cleanup EXIT

echo "=== Cloudflare IP Updater ==="

# Fetch IPv4 ranges
ipv4=$(curl -sf --max-time 15 "https://www.cloudflare.com/ips-v4/") || {
    echo "[ERROR] Failed to fetch IPv4 ranges" >&2
    exit 1
}

# Fetch IPv6 ranges
ipv6=$(curl -sf --max-time 15 "https://www.cloudflare.com/ips-v6/") || {
    echo "[ERROR] Failed to fetch IPv6 ranges" >&2
    exit 1
}

# Validate responses contain CIDR-like content
if [ -z "$ipv4" ] || ! echo "$ipv4" | grep -q '/'; then
    echo "[ERROR] IPv4 response does not look like valid CIDR ranges" >&2
    exit 1
fi
if [ -z "$ipv6" ] || ! echo "$ipv6" | grep -q '/'; then
    echo "[ERROR] IPv6 response does not look like valid CIDR ranges" >&2
    exit 1
fi

# Generate config atomically via temp file + mv
{
    cat <<HEADER
# =============================================================================
# Cloudflare, Restore Real Visitor IP
# =============================================================================
# Source: https://www.cloudflare.com/ips/
# Last updated: $(date +%Y-%m-%d), auto-generated by cf-update-ips.sh
# Auto-update: ./scripts/cf-update-ips.sh
# =============================================================================

# IPv4
HEADER
    while IFS= read -r cidr; do
        [ -n "$cidr" ] && echo "set_real_ip_from $cidr;"
    done <<< "$ipv4"

    echo ""
    echo "# IPv6"
    while IFS= read -r cidr; do
        [ -n "$cidr" ] && echo "set_real_ip_from $cidr;"
    done <<< "$ipv6"

    echo ""
    echo "real_ip_header CF-Connecting-IP;"
    echo "real_ip_recursive on;"
} > "$TMP_FILE"

mv -f "$TMP_FILE" "$CONF_FILE"

ipv4_count=$(echo "$ipv4" | wc -l)
ipv6_count=$(echo "$ipv6" | wc -l)
echo "  [OK] Updated $CONF_FILE ($ipv4_count IPv4, $ipv6_count IPv6 ranges)"
echo ""
echo "  Reload nginx to apply: docker compose exec nginx nginx -s reload"
